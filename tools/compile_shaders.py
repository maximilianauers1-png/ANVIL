"""Compiles app/render/shaders/*.{vert,frag} to SPIR-V and embeds them in
app/render/shaders/generated/shaders_spv.hpp (committed, so building ANVIL
does not need the Vulkan SDK). Requires glslangValidator on PATH.

    python tools/compile_shaders.py           # regenerate
    python tools/compile_shaders.py --check   # fail if the header is stale
"""
import os
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "app", "render", "shaders")
OUT = os.path.join(SRC, "generated", "shaders_spv.hpp")
STAGES = ["mesh.vert", "mesh.frag", "edge.vert", "edge.frag", "fullscreen.vert", "grid.frag", "composite.frag", "sky.frag"]


def build() -> str:
    parts = ["// Generated by tools/compile_shaders.py -- do not edit.", "#pragma once", "#include <cstdint>",
             "namespace anvil::spv {"]
    with tempfile.TemporaryDirectory() as d:
        for s in STAGES:
            out = os.path.join(d, s + ".spv")
            subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.1", "-o", out, s], cwd=SRC,
                           check=True, capture_output=True)
            data = open(out, "rb").read()
            words = struct.unpack(f"<{len(data) // 4}I", data)
            name = s.replace(".", "_")
            body = ",".join(f"0x{w:08x}u" for w in words)
            parts.append(f"inline constexpr std::uint32_t {name}[] = {{{body}}};")
    parts.append("}  // namespace anvil::spv\n")
    return "\n".join(parts)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        old = open(OUT).read() if os.path.exists(OUT) else ""
        sys.exit(0 if old == text else 1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(text)
    print("wrote", OUT)
